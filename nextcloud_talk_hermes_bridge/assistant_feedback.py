"""Compact helper-owned status messages and existing signed bot reactions."""
import threading
import time
from .secure_common import json_request


class TaskFeedback:
    RECEIVED_REACTION = '👀'
    QUEUED_NOTICE_DELAY = 15
    RUNNING_NOTICE_DELAY = 3
    RUNNING_NOTICE_INTERVAL = 180

    def init_feedback(self):
        self.feedback_lock = threading.Lock()
        self.feedback_wake = threading.Event()
        with self.db() as db:
            db.execute('CREATE TABLE IF NOT EXISTS task_feedback ('
                       'job_id TEXT PRIMARY KEY,received INTEGER NOT NULL DEFAULT 0,'
                       'receipt_attempts INTEGER NOT NULL DEFAULT 0,receipt_next REAL NOT NULL DEFAULT 0,'
                       'started REAL,next_notice REAL NOT NULL DEFAULT 0,queued_sent INTEGER NOT NULL DEFAULT 0)')
            db.execute('CREATE TABLE IF NOT EXISTS feedback_messages ('
                       'job_id TEXT PRIMARY KEY,uid TEXT,room TEXT,thread INTEGER,message_id INTEGER,'
                       'closed INTEGER NOT NULL DEFAULT 0,cleanup_attempts INTEGER NOT NULL DEFAULT 0,cleanup_next REAL NOT NULL DEFAULT 0)')

    def feedback_request(self,job,room,thread,phase,message=''):
        binding=self.bindings.get((job['uid'],room))
        if not binding:raise PermissionError('Unbound feedback destination')
        _,receipt=json_request(binding['runner_url']+'/feedback',method='POST',timeout=5,
            headers={'Authorization':'Bearer '+binding['runner_token']},
            body={'uid':job['uid'],'room':room,'thread':thread,'job_id':job['id'],'phase':phase,'message':message})
        return receipt

    def status_message(self,job,room,thread,message):
        with self.db() as db:old=db.execute('SELECT * FROM feedback_messages WHERE job_id=?',(job['id'],)).fetchone()
        if old and (old['uid'],old['room'],old['thread'])!=(job['uid'],room,thread):raise PermissionError('Feedback context changed')
        # Reserve before the HTTP call so a lost receipt can still be finalized.
        with self.db() as db:
            db.execute('INSERT OR IGNORE INTO feedback_messages (job_id,uid,room,thread,message_id) VALUES (?,?,?,?,0)',
                       (job['id'],job['uid'],room,thread))
        receipt=self.feedback_request(job,room,thread,'update',message)
        if type(receipt.get('message_id')) is not int or receipt['message_id']<=0:raise ValueError('Missing feedback receipt')
        with self.db() as db:
            db.execute('UPDATE feedback_messages SET message_id=? WHERE job_id=?',(receipt['message_id'],job['id']))

    def notification_feedback(self,row):
        # Notification IDs are generated by the Bridge, never by model text.
        job_id=row['id'].split('-',1)[0]
        with self.db() as db:
            old=db.execute('SELECT * FROM feedback_messages WHERE job_id=? AND closed=0',(job_id,)).fetchone()
            job=db.execute('SELECT * FROM jobs WHERE id=?',(job_id,)).fetchone()
        if not old or not job or row['reply'] or row['title']:return None
        if (old['uid'],old['room'],old['thread'])!=(job['uid'],row['room'],row['thread']):return None
        return job

    def close_feedback(self,job_id):
        with self.db() as db:db.execute('UPDATE feedback_messages SET closed=1 WHERE job_id=?',(job_id,))

    def cleanup_feedback(self,now):
        with self.db() as db:
            rows=db.execute("SELECT f.* FROM feedback_messages f JOIN jobs j ON j.id=f.job_id "
                "WHERE f.closed=0 AND f.cleanup_attempts<3 AND f.cleanup_next<=? "
                "AND j.status NOT IN ('queued','running') AND NOT EXISTS "
                "(SELECT 1 FROM notifications n WHERE n.id LIKE j.id||'-%' AND n.status='pending')",(now,)).fetchall()
        for old in rows:
            with self.db() as db:
                job=db.execute('SELECT * FROM jobs WHERE id=?',(old['job_id'],)).fetchone()
                db.execute('UPDATE feedback_messages SET cleanup_attempts=cleanup_attempts+1,cleanup_next=? WHERE job_id=?',(now+30,old['job_id']))
            if old['uid']!=job['uid'] or (job['uid'],job['room']) not in self.bindings:continue
            try:
                self.feedback_request(job,old['room'],old['thread'],'delete')
                self.close_feedback(job['id'])
            except Exception:pass
            return True
        return False

    def add_feedback(self, db, job_id, kind):
        if kind in ('task', 'answer'):
            db.execute('INSERT OR IGNORE INTO task_feedback (job_id) VALUES (?)', (job_id,))

    def start_feedback(self, db, job):
        if job['kind'] not in ('task', 'answer'):
            return
        now = time.time()
        # Old held requests may predate this feature. Do not re-acknowledge their old messages.
        db.execute('INSERT OR IGNORE INTO task_feedback (job_id,received) VALUES (?,2)', (job['id'],))
        db.execute('UPDATE task_feedback SET started=?,next_notice=? WHERE job_id=?',
                   (now, now + self.RUNNING_NOTICE_DELAY, job['id']))

    def finish_job(self, job_id, status, error=None):
        # Serialize finalization with bounded feedback sends. No running notice can be
        # sent after the job becomes terminal and the normal result is released.
        with self.feedback_lock:
            with self.db() as db:
                db.execute('UPDATE jobs SET status=?,error=? WHERE id=?', (status, error, job_id))
        self.feedback_wake.set()

    def feedback_destination(self, job):
        room = job['reply_room'] or job['room']
        thread = job['reply_thread'] if job['reply_room'] else job['thread']
        if (job['uid'], job['room']) not in self.bindings or (job['uid'], room) not in self.bindings:
            return None
        if type(thread) is not int or thread < 0 or type(job['message_id']) is not int or job['message_id'] <= 0:
            return None
        return room, thread

    def flush_feedback(self, now=None):
        now = time.time() if now is None else now
        with self.feedback_lock:
            with self.db() as db:
                rows = db.execute("SELECT j.*,f.received,f.receipt_attempts,f.receipt_next,f.started,f.next_notice,f.queued_sent "
                                  "FROM task_feedback f JOIN jobs j ON j.id=f.job_id "
                                  "WHERE j.kind IN ('task','answer') AND j.status IN ('queued','running','awaiting_onboarding') "
                                  "ORDER BY j.created,j.rowid").fetchall()
            for job in rows:
                destination = self.feedback_destination(job)
                if destination is None:
                    continue
                room, thread = destination
                phase = None
                if job['received'] == 0 and job['receipt_attempts'] < 3 and job['receipt_next'] <= now:
                    phase = 'received'
                    with self.db() as db:
                        db.execute('UPDATE task_feedback SET receipt_attempts=receipt_attempts+1,receipt_next=? WHERE job_id=?',
                                   (now + 30, job['id']))
                elif job['status'] == 'queued' and not job['queued_sent'] and now - job['created'] >= self.QUEUED_NOTICE_DELAY:
                    phase = 'queued'
                    message = '已收到，正在排队；轮到这条请求时会开始处理。'
                    with self.db() as db:
                        db.execute('UPDATE task_feedback SET queued_sent=1 WHERE job_id=?', (job['id'],))
                elif job['status'] == 'running' and job['started'] is not None and job['next_notice'] <= now:
                    phase = 'running'
                    elapsed = max(0, int(now - job['started']))
                    if job['next_notice'] <= job['started'] + self.RUNNING_NOTICE_DELAY:
                        message = '正在处理当前请求，完成后会在这里回复。'
                    else:
                        message = '仍在处理当前请求，已运行约 ' + str(max(1, elapsed // 60)) + ' 分钟；完成后会在这里回复。'
                    # Status text is attempted at most once per interval. A failed notice
                    # must never rerun a model task or flood the conversation on recovery.
                    with self.db() as db:
                        db.execute('UPDATE task_feedback SET next_notice=? WHERE job_id=?',
                                   (now + self.RUNNING_NOTICE_INTERVAL, job['id']))
                if phase is None:
                    continue
                try:
                    if phase == 'received':
                        self.react(room, job['message_id'], self.RECEIVED_REACTION, timeout=5)
                        with self.db() as db:
                            db.execute('UPDATE task_feedback SET received=1 WHERE job_id=?', (job['id'],))
                    else:
                        self.status_message(job,room,thread,message)
                except Exception:
                    # Optional UI feedback carries no authority. It cannot fail a job,
                    # consume a choice, or log credentials, prompts or other user data.
                    pass
                return True
            return self.cleanup_feedback(now)

    def work_feedback(self):
        while not self.stop.is_set():
            self.feedback_wake.clear()
            try:
                if self.flush_feedback():
                    continue
            except Exception:
                pass
            self.feedback_wake.wait(.5)
